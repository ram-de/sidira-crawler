"""Adapter: simulator dispatch payload (``config_json``) → ``CustomerConfig``.

The simulator backend sends a non-secret ``config_json`` over
``workflow_dispatch`` (sidira-simulator #206; the shape is
``CrawlSetup.dispatch_payload``): ``sandbox_url``, ``walk_depth``,
``capabilities[{name, entry_urls}]``, and a top-level ``roles`` list.

Credentials are deliberately NOT in that payload. They arrive separately in the
``SIDIRA_CRAWL_CREDENTIALS`` env var, pulled from an authenticated backend
endpoint at run start (#206 Slice C) and masked before reaching any log line.

This module fuses the two halves into the crawler's own
:class:`~sidira_crawler.config.CustomerConfig` so the production walk can run
through :func:`~sidira_crawler.crawler.run_crawl` (#23). It maps the dispatch
field names onto the config's, fans the top-level roles across every capability,
honors ``walk_depth`` as each capability's hop budget, and exports each role's
login to the per-role env vars the walker resolves by name.
"""

from __future__ import annotations

import json
import os

from sidira_crawler.config import CapabilityConfig, CustomerConfig, RoleCredential
from sidira_crawler.storage import validate_product_id

CREDENTIALS_ENV = "SIDIRA_CRAWL_CREDENTIALS"


def build_customer_config(payload: dict, customer_id: str) -> CustomerConfig:
    """Translate a dispatch ``config_json`` payload into a ``CustomerConfig``.

    Credential *secrets* are not touched here — only the env-var *names* the
    walker will read are assigned (see :func:`apply_pulled_credentials`). The
    names are generated by role index, not the free-form role string, so they
    are collision-free shell identifiers without sanitizing.
    """
    sandbox_url = (payload.get("sandbox_url") or "").strip()
    if not sandbox_url:
        raise ValueError("dispatch config_json is missing sandbox_url")

    # Which crawl setup this org dispatched (sidira-simulator #215/#245). Absent
    # or empty → "default" (the legacy single-setup org, byte-identical R2 path).
    # Validate as a safe R2-key slug (shared with storage's enforcement point) so
    # it can never escape the key.
    product_id = (payload.get("product_id") or "default").strip()
    try:
        validate_product_id(product_id)
    except ValueError as exc:
        raise ValueError(f"dispatch config_json has an {exc}") from exc

    roles = list(payload.get("roles") or [])
    if not roles:
        raise ValueError("dispatch config_json declares no roles")

    raw_caps = payload.get("capabilities") or []
    if not raw_caps:
        raise ValueError("dispatch config_json declares no capabilities")

    # walk_depth is the customer's chosen hop budget (2–4, sidira-simulator
    # CrawlSetup). Honor it as every capability's max_hops so the saved setup
    # demonstrably drives the production walk. The config's default of 6 applies
    # only to the checked-in YAML cron path, never to a dispatched crawl. (#23)
    default_hops = CapabilityConfig.model_fields["max_hops"].default
    walk_depth = int(payload.get("walk_depth", default_hops))

    role_credentials = [
        RoleCredential(
            role=role,
            env_var_user=f"SIDIRA_CRED_USER_{i}",
            env_var_password=f"SIDIRA_CRED_PASS_{i}",
        )
        for i, role in enumerate(roles)
    ]

    capabilities = [
        CapabilityConfig(
            name=cap["name"],
            entry_points=list(cap["entry_urls"]),
            roles=roles,
            max_hops=walk_depth,
        )
        for cap in raw_caps
    ]

    return CustomerConfig(
        customer_id=customer_id,
        sandbox_base_url=sandbox_url,
        product_id=product_id,
        capabilities=capabilities,
        role_credentials=role_credentials,
    )


def apply_pulled_credentials(config: CustomerConfig, environ: dict | None = None) -> list[str]:
    """Export each role's pulled login to the env vars ``config`` references.

    Reads the ``SIDIRA_CRAWL_CREDENTIALS`` JSON
    (``{"logins": [{"role", "username", "password"}, ...]}``) and writes each
    role's username/password into the ``env_var_user``/``env_var_password`` names
    assigned by :func:`build_customer_config`. Returns the sorted role names that
    received credentials.

    A production dispatch lists only roles that have a stored login (every
    simulator ``test_user`` carries a password), so the pull MUST cover every
    role: a missing role — or an absent/empty env var — raises rather than
    walking that role unauthenticated, which would otherwise surface as a
    confusing honesty-gate coverage failure instead of a clear setup error.
    This mirrors the mock path's authoritative-pull semantics
    (``scripts/sandbox_acceptance.py``).
    """
    env = os.environ if environ is None else environ
    raw = (env.get(CREDENTIALS_ENV) or "").strip()
    if not raw:
        raise ValueError(
            f"{CREDENTIALS_ENV} is empty — a production crawl needs a stored "
            "login for every role; re-save the crawl setup so credentials are "
            "delivered, or the run cannot authenticate"
        )
    try:
        logins = json.loads(raw)["logins"]
        pulled = {lg["role"]: (lg["username"], lg["password"]) for lg in logins}
    except (json.JSONDecodeError, KeyError, TypeError) as exc:
        raise ValueError(f"{CREDENTIALS_ENV} is not valid credential JSON: {exc}") from exc

    needed = {c.role for c in config.role_credentials}
    missing = sorted(needed - pulled.keys())
    if missing:
        raise ValueError(
            f"{CREDENTIALS_ENV} delivered logins for {sorted(pulled)} but the "
            f"crawl needs logins for {missing} — re-save the crawl setup so "
            "every role has stored credentials"
        )

    applied: list[str] = []
    for cred in config.role_credentials:
        username, password = pulled[cred.role]
        env[cred.env_var_user] = username
        env[cred.env_var_password] = password
        applied.append(cred.role)
    return sorted(applied)
